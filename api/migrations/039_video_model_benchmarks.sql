CREATE TABLE IF NOT EXISTS video_model_benchmarks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  job_id uuid NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  approval_id uuid NOT NULL,
  slot text NOT NULL,
  scene_id text NOT NULL,
  endpoint_id text NOT NULL,
  model_name text NOT NULL,
  scene_type text NOT NULL,
  original_prompt text NOT NULL,
  compiled_prompt text NOT NULL,
  knowledge_version text,
  generation_params jsonb NOT NULL,
  generation_seconds numeric NOT NULL,
  edited_seconds numeric NOT NULL,
  estimated_usd numeric NOT NULL,
  actual_usd numeric,
  generation_ms bigint,
  generated_duration numeric,
  artifact_key text,
  request_id text,
  status text NOT NULL DEFAULT 'pending',
  failure_reason text,
  quality jsonb,
  qa_response_id text,
  qa_usage jsonb,
  user_rating integer CHECK (user_rating BETWEEN 1 AND 5),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(job_id, slot, approval_id)
);
CREATE INDEX IF NOT EXISTS video_model_benchmarks_model_idx ON video_model_benchmarks(endpoint_id, scene_type, created_at DESC);
